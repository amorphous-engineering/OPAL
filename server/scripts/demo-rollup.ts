#!/usr/bin/env bun
/**
 * Adds up what every procedure in the demo dataset draws for one vehicle and one set of ground
 * equipment, and writes KIT-ROLLUP.md beside the dataset: the shopping list the procedures imply.
 *
 *   bun scripts/demo-rollup.ts [dataset-dir]
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { convert } from '@opal/shared';

type Rec = Record<string, any>;
const dataset = resolve(process.argv[2] ?? join(import.meta.dir, '../../demo/mojave-sphinx'));
const yaml = (f: string): Rec => Bun.YAML.parse(readFileSync(join(dataset, f), 'utf8')) as Rec;
const parts = new Map<string, Rec>(yaml('parts.yaml').parts.map((p: Rec) => [p.key, p]));
const procedures: Rec[] = readdirSync(join(dataset, 'procedures'))
	.filter((f) => f.endsWith('.yaml'))
	.sort()
	.map((f) => yaml(join('procedures', f)));

/** Every kit line of a procedure file: the procedure's own, then each step's. */
const kitLines = (p: Rec): Rec[] => [...(p.kit ?? []), ...(p.operations as Rec[]).flatMap((o) => ((o.steps ?? []) as Rec[]).flatMap((x) => (x.kit ?? []) as Rec[]))];
const outputsOf = (p: Rec): Rec[] => p.outputs ?? (p.output ? [p.output] : []);
const makes = new Map<string, Rec>();
for (const p of procedures) for (const o of outputsOf(p)) makes.set(o.part, p);

/** How many times each procedure runs to end with one vehicle, one ground system and its cables. */
const runs = new Map<string, number>();
function need(partKey: string, quantity: number) {
	const p = makes.get(partKey);
	if (!p) return;
	// A procedure with several products makes them all in one run.
	const have = runs.get(p.key) ?? 0;
	const want = outputsOf(p).length > 1 ? Math.max(have, 1) : have + quantity;
	if (want === have) return;
	runs.set(p.key, want);
	for (const k of kitLines(p)) if ((k.usage ?? 'consume') === 'consume') need(k.part, Number(k.quantity) * (want - have));
}
for (const top of ['mojave-sphinx', 'gse-system', 'purge-system', 'gse-servo-cable']) need(top, 1);
// Operating procedures run once each.
for (const p of procedures) if (p.type === 'op') runs.set(p.key, 1);

const total = new Map<string, { quantity: number; where: string[] }>();
for (const p of procedures) {
	const times = runs.get(p.key) ?? 0;
	if (!times) continue;
	for (const k of kitLines(p)) {
		if (makes.has(k.part) || (k.usage ?? 'consume') !== 'consume') continue;
		const part = parts.get(k.part);
		if (!part) throw new Error(`${p.key}: no part '${k.part}'`);
		const unit = part.unit ?? 'ea';
		const each = !k.unit || k.unit === unit ? Number(k.quantity) : convert(Number(k.quantity), k.unit, unit);
		const row = total.get(k.part) ?? { quantity: 0, where: [] };
		row.quantity += each * times;
		const where = times > 1 ? `${p.name} ×${times}` : p.name;
		if (!row.where.includes(where)) row.where.push(where);
		total.set(k.part, row);
	}
}

const round = (n: number) => String(Number(n.toFixed(3)));
const lines: string[] = [
	'# What the procedures draw',
	'',
	'Generated by `bun scripts/demo-rollup.ts` in `server/` from the kits in `procedures/`. Edit those, not this file.',
	'',
	'One vehicle, one ground system with the optional purge system, and one set of cables and fill',
	'line. Sub-assemblies are followed down to the parts they are built from. Tooling is left out.',
	'',
	'## How many times each procedure runs',
	'',
	'| Procedure | Runs |',
	'|---|---|',
	...procedures.filter((p) => runs.get(p.key)).map((p) => `| ${p.name} | ${runs.get(p.key)} |`),
	'',
	'## Bought parts',
	'',
	'"Packs" is the draw divided by the pack size on file, rounded up. A blank means no pack size is on file.',
	'',
	'| Part | Name | Draw | Unit | Packs | Used in |',
	'|---|---|---|---|---|---|'
];
const cell = (s: string) => s.replaceAll('|', '\\|');
const rows = [...total].sort(([a], [b]) => a.localeCompare(b));
for (const [key, row] of rows) {
	const p = parts.get(key)!;
	if (p.procurement !== 'buy') continue;
	const pack = p.supplier?.pack ? String(Math.ceil(row.quantity / Number(p.supplier.pack))) : '';
	lines.push(`| ${cell(key)} | ${cell(p.name)} | ${round(row.quantity)} | ${p.unit ?? 'ea'} | ${pack} | ${cell(row.where.join(', '))} |`);
}
lines.push('', '## Parts the team makes, with no procedure here', '', '| Part | Name | Draw | Made from | Used in |', '|---|---|---|---|---|');
for (const [key, row] of rows) {
	const p = parts.get(key)!;
	if (p.procurement !== 'make') continue;
	lines.push(`| ${cell(key)} | ${cell(p.name)} | ${round(row.quantity)} | ${cell(p.made_from ?? '')} | ${cell(row.where.join(', '))} |`);
}
const unused = [...parts.values()].filter((p) => !total.has(p.key) && !makes.has(p.key) && !procedures.some((x) => kitLines(x).some((k: Rec) => k.part === p.key)));
lines.push('', '## Parts on file that no procedure draws', '', 'In the bills of material or a parts list, but in no kit. Some are tools, spares or options.', '', '| Part | Name | Source |', '|---|---|---|');
for (const p of unused) lines.push(`| ${cell(p.key)} | ${cell(p.name)} | ${cell(String(p.source ?? ''))} |`);
writeFileSync(join(dataset, 'KIT-ROLLUP.md'), lines.join('\n') + '\n');
console.log(`${rows.length} parts drawn, ${unused.length} on file and not drawn`);
