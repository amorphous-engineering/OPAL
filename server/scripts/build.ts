/**
 * Builds the `opal` binaries: the web client and the migrations are embedded.
 * Usage: bun scripts/build.ts [--target bun-darwin-arm64] [--version 1.2.3]
 * Run `pnpm --filter frontend build` first.
 */
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';

const root = resolve(import.meta.dir, '..');
const clientDir = resolve(root, '../frontend/build');
const drizzleDir = join(root, 'drizzle');
const genDir = join(root, 'src/generated');
const distDir = join(root, 'dist');

const TARGETS: Record<string, string> = {
	'bun-darwin-arm64': 'opal-macos-arm64',
	'bun-darwin-x64': 'opal-macos-x86_64',
	'bun-linux-x64': 'opal-linux-x86_64',
	'bun-linux-arm64': 'opal-linux-arm64',
	'bun-windows-x64': 'opal-windows-x86_64.exe'
};

function arg(name: string): string | undefined {
	const i = process.argv.indexOf(`--${name}`);
	return i >= 0 ? process.argv[i + 1] : undefined;
}

function fail(message: string): never {
	console.error(`error: ${message}`);
	process.exit(1);
}

function walk(dir: string): string[] {
	return readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
		e.isDirectory() ? walk(join(dir, e.name)) : [join(dir, e.name)]
	);
}

const slash = (p: string) => p.split('\\').join('/');

/** Writes the entry module that sets the embedded assets, then loads the CLI. */
function generate(): string {
	if (!existsSync(join(clientDir, 'index.html'))) {
		fail('frontend/build/index.html is missing. Run `pnpm --filter frontend build` first.');
	}
	rmSync(genDir, { recursive: true, force: true });
	mkdirSync(genDir, { recursive: true });

	const files = walk(clientDir).sort();
	const imports = files.map(
		(f, i) => `import f${i} from ${JSON.stringify(slash(relative(genDir, f)))} with { type: 'file' };`
	);
	const web = files.map((f, i) => `\t\t${JSON.stringify(slash(relative(clientDir, f)))}: f${i}`);

	// Same record shape as drizzle's readMigrationFiles, computed at build time.
	const journal = JSON.parse(readFileSync(join(drizzleDir, 'meta/_journal.json'), 'utf8')) as {
		entries: { tag: string; when: number; breakpoints: boolean }[];
	};
	const migrations = journal.entries.map((e) => {
		const query = readFileSync(join(drizzleDir, `${e.tag}.sql`), 'utf8');
		return {
			sql: query.split('--> statement-breakpoint'),
			bps: e.breakpoints,
			folderMillis: e.when,
			hash: createHash('sha256').update(query).digest('hex')
		};
	});

	const entry = join(genDir, 'entry.ts');
	writeFileSync(
		entry,
		`// @ts-nocheck
// Generated by scripts/build.ts. Do not edit.
${imports.join('\n')}
import demoSeed from '../../assets/demo-seed.db' with { type: 'file' };

globalThis.__opalEmbedded = {
	demoSeed,
	migrations: ${JSON.stringify(migrations)},
	web: {
${web.join(',\n')}
	}
};

await import('../cli.ts');
`
	);
	console.log(`embedding ${files.length} client files and ${migrations.length} migrations`);
	return entry;
}

const version = arg('version')?.replace(/^v/, '') ?? '0.0.0-dev';
const only = arg('target');
if (only && !TARGETS[only]) fail(`unknown target ${only}. Targets: ${Object.keys(TARGETS).join(', ')}`);

const entry = generate();
mkdirSync(distDir, { recursive: true });

// One after another: each compile needs a lot of memory.
for (const [target, asset] of Object.entries(TARGETS)) {
	if (only && only !== target) continue;
	console.log(`building ${asset} (${target}, version ${version})`);
	const proc = Bun.spawnSync(
		[
			'bun', 'build', '--compile', '--minify', '--sourcemap',
			`--target=${target}`,
			'--define', `OPAL_VERSION=${JSON.stringify(version)}`,
			entry,
			'--outfile', join(distDir, asset)
		],
		{ cwd: root, stdout: 'inherit', stderr: 'inherit' }
	);
	if (proc.exitCode !== 0) fail(`bun build failed for ${target}`);
}

const sums = Object.values(TARGETS)
	.filter((asset) => existsSync(join(distDir, asset)))
	.map((asset) => {
		const hash = createHash('sha256').update(readFileSync(join(distDir, asset))).digest('hex');
		return `${hash}  ${asset}`;
	});
writeFileSync(join(distDir, 'SHA256SUMS'), `${sums.join('\n')}\n`);
console.log(sums.join('\n'));
